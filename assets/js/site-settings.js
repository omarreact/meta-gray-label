(() => {
  'use strict';

  const script = document.currentScript;
  const siteRoot = new URL('../../', script?.src || document.baseURI);
  const configUrl = new URL('assets/site-settings.json', siteRoot);
  const localKey = 'mgl-dev-font-preference-v1';
  const repoIssueUrl = 'https://github.com/omarreact/meta-gray-label/issues/new';

  const fonts = [
    { family: 'Arial', label: 'Arial / Helvetica — Reference', provider: 'system' },
    { family: 'Inter', label: 'Inter', provider: 'google' },
    { family: 'Roboto', label: 'Roboto', provider: 'google' },
    { family: 'Open Sans', label: 'Open Sans', provider: 'google' },
    { family: 'Lato', label: 'Lato', provider: 'google' },
    { family: 'Montserrat', label: 'Montserrat', provider: 'google' },
    { family: 'Poppins', label: 'Poppins', provider: 'google' },
    { family: 'Nunito Sans', label: 'Nunito Sans', provider: 'google' },
    { family: 'DM Sans', label: 'DM Sans', provider: 'google' },
    { family: 'Manrope', label: 'Manrope', provider: 'google' },
    { family: 'Work Sans', label: 'Work Sans', provider: 'google' },
    { family: 'Source Sans 3', label: 'Source Sans 3', provider: 'google' },
    { family: 'Merriweather', label: 'Merriweather', provider: 'google' },
    { family: 'Playfair Display', label: 'Playfair Display', provider: 'google' }
  ];

  const allowed = new Map(fonts.map(font => [font.family, font]));
  let projectSetting = { globalFontFamily: 'Arial', provider: 'system' };
  let draftSetting = { ...projectSetting };

  function normalizeSetting(value) {
    const family = typeof value?.globalFontFamily === 'string' ? value.globalFontFamily : 'Arial';
    const match = allowed.get(family) || allowed.get('Arial');
    return { globalFontFamily: match.family, provider: match.provider };
  }

  function fontStack(setting) {
    if (setting.provider === 'google') {
      return '"' + setting.globalFontFamily.replace(/"/g, '') + '",Arial,Helvetica,sans-serif';
    }
    return 'Arial,Helvetica,sans-serif';
  }

  function googleCss2Url(family) {
    const encoded = family.trim().replace(/\s+/g, '+');
    return 'https://fonts.googleapis.com/css2?family=' + encoded + ':wght@400;500;600;700;800&display=swap';
  }

  function loadGoogleFont(setting) {
    const existing = document.getElementById('mgl-google-font-runtime');
    if (setting.provider !== 'google') {
      existing?.remove();
      return;
    }

    const href = googleCss2Url(setting.globalFontFamily);
    if (existing?.href === href) return;

    existing?.remove();
    const link = document.createElement('link');
    link.id = 'mgl-google-font-runtime';
    link.rel = 'stylesheet';
    link.href = href;
    link.crossOrigin = 'anonymous';
    document.head.appendChild(link);
  }

  function applySetting(setting) {
    const normalized = normalizeSetting(setting);
    loadGoogleFont(normalized);
    document.documentElement.style.setProperty('--mgl-global-font-family', fontStack(normalized));
    document.documentElement.dataset.mglFontFamily = normalized.globalFontFamily;
    draftSetting = { ...normalized };

    const preview = document.querySelector('[data-mgl-font-preview]');
    if (preview) preview.style.fontFamily = fontStack(normalized);

    const source = document.querySelector('[data-mgl-font-source]');
    if (source) {
      source.textContent = normalized.provider === 'google'
        ? 'Google Fonts CSS2 API · weights 400–800'
        : 'System font stack · no external request';
    }
    return normalized;
  }

  function readLocalSetting() {
    try {
      const raw = localStorage.getItem(localKey);
      return raw ? normalizeSetting(JSON.parse(raw)) : null;
    } catch (_) {
      return null;
    }
  }

  function saveLocalSetting(setting) {
    localStorage.setItem(localKey, JSON.stringify(normalizeSetting(setting)));
  }

  function setStatus(message, tone = 'ok') {
    const status = document.querySelector('[data-mgl-settings-status]');
    if (!status) return;
    status.textContent = message;
    status.style.color = tone === 'error' ? '#ff9c9c' : '#7fe7ce';
  }

  function buildIssueUrl(setting) {
    const normalized = normalizeSetting(setting);
    const payload = JSON.stringify({
      globalFontFamily: normalized.globalFontFamily,
      provider: normalized.provider
    });
    const title = '[Site Settings] Global font: ' + normalized.globalFontFamily;
    const body = [
      '<!-- MGL_SITE_SETTINGS_V1',
      payload,
      '-->',
      '### Global typography setting',
      '',
      '- Font family: **' + normalized.globalFontFamily + '**',
      '- Provider: **' + normalized.provider + '**',
      '',
      'This issue was generated by the Meta Grey Label developer settings panel.',
      'Only the repository owner can trigger the protected settings workflow.',
      '',
      'Submit this issue to write the setting into the codebase and trigger normal validation/deployment.'
    ].join('\n');

    const url = new URL(repoIssueUrl);
    url.searchParams.set('title', title);
    url.searchParams.set('body', body);
    return url.href;
  }

  function closePanel(restoreFocus = true) {
    document.documentElement.classList.remove('mgl-settings-open');
    const panel = document.getElementById('mgl-dev-settings-panel');
    const toggle = document.getElementById('mgl-dev-settings-toggle');
    panel?.setAttribute('aria-hidden', 'true');
    toggle?.setAttribute('aria-expanded', 'false');
    if (restoreFocus) toggle?.focus({ preventScroll: true });
  }

  function openPanel() {
    document.documentElement.classList.add('mgl-settings-open');
    const panel = document.getElementById('mgl-dev-settings-panel');
    const toggle = document.getElementById('mgl-dev-settings-toggle');
    panel?.setAttribute('aria-hidden', 'false');
    toggle?.setAttribute('aria-expanded', 'true');
    panel?.querySelector('select')?.focus({ preventScroll: true });
  }

  function createUi(activeSetting) {
    if (document.getElementById('mgl-dev-settings-toggle')) return;

    const toggle = document.createElement('button');
    toggle.id = 'mgl-dev-settings-toggle';
    toggle.className = 'mgl-dev-settings-toggle';
    toggle.type = 'button';
    toggle.setAttribute('aria-label', 'Open developer site settings');
    toggle.setAttribute('aria-controls', 'mgl-dev-settings-panel');
    toggle.setAttribute('aria-expanded', 'false');
    toggle.innerHTML = '<svg aria-hidden="true" viewBox="0 0 24 24"><path d="M12 8.5a3.5 3.5 0 1 0 0 7 3.5 3.5 0 0 0 0-7Z"/><path d="M19.2 13.2a7.6 7.6 0 0 0 0-2.4l2-1.5-2-3.5-2.4 1a8.6 8.6 0 0 0-2.1-1.2L14.4 3h-4.1L10 5.6a8.6 8.6 0 0 0-2.1 1.2l-2.4-1-2 3.5 2 1.5a7.6 7.6 0 0 0 0 2.4l-2 1.5 2 3.5 2.4-1a8.6 8.6 0 0 0 2.1 1.2l.3 2.6h4.1l.3-2.6a8.6 8.6 0 0 0 2.1-1.2l2.4 1 2-3.5-2-1.5Z"/></svg>';

    const panel = document.createElement('aside');
    panel.id = 'mgl-dev-settings-panel';
    panel.className = 'mgl-dev-settings-panel';
    panel.setAttribute('aria-label', 'Developer site settings');
    panel.setAttribute('aria-hidden', 'true');

    const options = fonts.map(font =>
      '<option value="' + font.family.replace(/"/g, '&quot;') + '">' + font.label + '</option>'
    ).join('');

    panel.innerHTML = `
      <div class="mgl-dev-settings-head">
        <div>
          <span class="mgl-dev-settings-kicker">Developer controls</span>
          <h2 class="mgl-dev-settings-title">Site Settings</h2>
        </div>
        <button class="mgl-dev-settings-close" type="button" aria-label="Close site settings" data-mgl-settings-close>×</button>
      </div>
      <div class="mgl-dev-settings-body">
        <section class="mgl-dev-settings-section">
          <label class="mgl-dev-settings-label" for="mgl-global-font-select">Global font family</label>
          <select class="mgl-dev-settings-select" id="mgl-global-font-select" data-mgl-font-select>
            ${options}
          </select>
          <div class="mgl-dev-settings-meta">
            <span class="mgl-dev-settings-dot" aria-hidden="true"></span>
            <span data-mgl-font-source></span>
          </div>
          <div class="mgl-dev-font-preview" data-mgl-font-preview>
            <strong>Meta Grey Label</strong>
            <span>Brokerage technology, liquidity, CRM and platform infrastructure.</span>
          </div>
          <div class="mgl-dev-settings-actions">
            <button class="mgl-dev-settings-button" type="button" data-mgl-save-device>Save on device</button>
            <button class="mgl-dev-settings-button" type="button" data-mgl-reset-font>Reset</button>
            <button class="mgl-dev-settings-button mgl-dev-settings-button--primary mgl-dev-settings-button--wide" type="button" data-mgl-save-codebase>Save to codebase → GitHub</button>
          </div>
          <p class="mgl-dev-settings-note">
            Selecting a font previews it immediately. Device save uses localStorage. Codebase save opens a protected owner-only GitHub workflow request; no GitHub token is exposed in this page.
          </p>
          <p class="mgl-dev-settings-status" role="status" aria-live="polite" data-mgl-settings-status></p>
        </section>
      </div>
      <div class="mgl-dev-settings-footer">
        Google Fonts are loaded through the CSS2 API only when a Google family is selected.
      </div>
    `;

    document.body.append(toggle, panel);

    const select = panel.querySelector('[data-mgl-font-select]');
    select.value = activeSetting.globalFontFamily;

    toggle.addEventListener('click', openPanel);
    panel.querySelector('[data-mgl-settings-close]')?.addEventListener('click', () => closePanel());

    select.addEventListener('change', () => {
      const next = normalizeSetting({ globalFontFamily: select.value });
      applySetting(next);
      setStatus('Preview applied. Save when you are satisfied.');
    });

    panel.querySelector('[data-mgl-save-device]')?.addEventListener('click', () => {
      saveLocalSetting(draftSetting);
      setStatus('Saved on this device. This preference will follow you across site pages.');
    });

    panel.querySelector('[data-mgl-reset-font]')?.addEventListener('click', () => {
      localStorage.removeItem(localKey);
      select.value = projectSetting.globalFontFamily;
      applySetting(projectSetting);
      setStatus('Reset to the current codebase setting.');
    });

    panel.querySelector('[data-mgl-save-codebase]')?.addEventListener('click', () => {
      saveLocalSetting(draftSetting);
      if (draftSetting.globalFontFamily === projectSetting.globalFontFamily &&
          draftSetting.provider === projectSetting.provider) {
        setStatus('This font is already the current codebase setting.');
        return;
      }
      const popup = window.open(buildIssueUrl(draftSetting), '_blank', 'noopener,noreferrer');
      if (!popup) {
        setStatus('Popup blocked. Allow popups for this site and try again.', 'error');
        return;
      }
      setStatus('GitHub opened. Submit the prefilled issue to publish this setting to main.');
    });

    document.addEventListener('keydown', event => {
      if (event.key === 'Escape' && document.documentElement.classList.contains('mgl-settings-open')) {
        closePanel();
      }
    });
  }

  async function init() {
    try {
      const response = await fetch(configUrl, { cache: 'no-store' });
      if (response.ok) {
        const config = await response.json();
        projectSetting = normalizeSetting(config?.typography || config);
      }
    } catch (_) {
      projectSetting = { globalFontFamily: 'Arial', provider: 'system' };
    }

    const localSetting = readLocalSetting();
    const active = applySetting(localSetting || projectSetting);
    createUi(active);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init, { once: true });
  } else {
    init();
  }
})();
